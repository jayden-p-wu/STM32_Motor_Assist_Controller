/* fardriver.c
 * Fardriver ND-series motor controller interface.
 * Controls throttle via DAC1_OUT1, regen brake and key via GPIO.
 */

#include "fardriver.h"

extern DAC_HandleTypeDef hdac1;  /* Generated by CubeMX as hdac1 */
#define hdac hdac1              /* alias so the rest of this file is unchanged */

void Fardriver_Init(void)
{
    HAL_DAC_Start(&hdac, DAC_CHANNEL_1);

    /* Start with key off, no throttle, no regen */
    Fardriver_SetKey(0);
    Fardriver_SetThrottle(0.0f);
    Fardriver_SetRegenBrake(0);
}

void Fardriver_SetThrottle(float percent)
{
    if (percent < 0.0f)   percent = 0.0f;
    if (percent > 100.0f) percent = 100.0f;

    uint32_t dac_val = FARDRIVER_DAC_IDLE
        + (uint32_t)((percent / 100.0f) * (float)(FARDRIVER_DAC_FULL - FARDRIVER_DAC_IDLE));

    HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, dac_val);
}

void Fardriver_SetKey(uint8_t on)
{
    HAL_GPIO_WritePin(FARDRIVER_KEY_GPIO_Port, FARDRIVER_KEY_Pin,
                      on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

void Fardriver_SetRegenBrake(uint8_t engage)
{
    /* Active-high output drives the gate of an N-channel FET.
     * The FET drain connects to Fardriver BL (low-voltage brake, pin 20),
     * source to GND.  When FET is on, BL is pulled to GND = regen enabled. */
    HAL_GPIO_WritePin(REGEN_BRAKE_GPIO_Port, REGEN_BRAKE_Pin,
                      engage ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

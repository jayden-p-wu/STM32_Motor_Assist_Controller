/* fardriver.c
 * Fardriver ND-series motor controller interface.
 * Controls throttle via PWM, regen brake and key via GPIO.
 */

#include "fardriver.h"

extern TIM_HandleTypeDef htim3;  /* Generated by CubeMX for TIM3 PWM */

void Fardriver_Init(void)
{
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);

    Fardriver_SetKey(0);
    Fardriver_SetThrottle(0.0f);
    Fardriver_SetRegenBrake(0);
}

double Fardriver_SetThrottle(float percent)
{
    if (percent < 0.0f)   percent = 0.0f;
    if (percent > 100.0f) percent = 100.0f;

    float target_voltage = FARDRIVER_THROTTLE_MIN_V 
        + ((percent / 100.0f) * (FARDRIVER_THROTTLE_MAX_V - FARDRIVER_THROTTLE_MIN_V));

    uint32_t pwm_val = (uint32_t)((target_voltage / 3.3f) * PWM_RESOLUTION);

    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pwm_val);

    return (double)pwm_val;
}

void Fardriver_SetKey(uint8_t on)
{
    HAL_GPIO_WritePin(FARDRIVER_KEY_GPIO_Port, FARDRIVER_KEY_Pin,
                      on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

void Fardriver_SetRegenBrake(uint8_t engage)
{
    /* PC8 is configured GPIO_MODE_OUTPUT_OD and wired directly to Fardriver
     * BL (low-voltage brake, pin 20) - no external FET. Controller is
     * confirmed configured for Mode A (GND = Park/Brake, float = Drive),
     * so "engage" directly means "pull BL to GND". */
    uint8_t want_grounded = engage;
    /* Open-drain write polarity is inverted vs push-pull: RESET (0) turns
     * the pin's internal NMOS ON, pulling it to GND; SET (1) turns it OFF,
     * leaving the pin floating (Hi-Z). */
    HAL_GPIO_WritePin(REGEN_BRAKE_GPIO_Port, REGEN_BRAKE_Pin,
                      want_grounded ? GPIO_PIN_RESET : GPIO_PIN_SET);
}
